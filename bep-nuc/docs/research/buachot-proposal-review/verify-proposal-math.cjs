const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const b = 0.05, C = 3000, m = 2000;
const scenarios = [30000, 50000, 100000].map(P => {
  const F = 0.65 * P;
  const Q = (1 - b) * P;
  const maxVoucher = 1 - (F + C + m) / Q;
  const paymentAtCap = F + C + m;
  return { original: P, shopNet: F, variableCost: C, requiredContribution: m, maxVoucher, paymentAtCap, totalDiscountAtCap: 1 - paymentAtCap / P, voucher20Eligible: Q * 0.8 >= F + C + m };
});
assert.equal(scenarios[0].voucher20Eligible, false);
assert.equal(scenarios[1].voucher20Eligible, true);
assert.equal(scenarios[2].voucher20Eligible, true);
assert.deepEqual(scenarios.map(x => x.paymentAtCap), [24500, 37500, 70000]);
assert.ok(Math.abs(scenarios[0].maxVoucher - 0.14035087719298245) < 1e-12);
assert.ok(Math.abs(scenarios[2].totalDiscountAtCap - 0.30) < 1e-12);
assert.ok(Math.abs(scenarios[2].maxVoucher - scenarios[2].totalDiscountAtCap) > 0.03);
const maxFloorFor30kAt20 = 30000 * 0.95 * 0.8 - C - m;
assert.equal(maxFloorFor30kAt20, 17800);
const extraSavingsAt1km = [30000, 100000].map(P => P * 0.95 * 0.08);
assert.deepEqual(extraSavingsAt1km, [2280, 7600]);
const controlMargin = 100000 * 0.95 * 0.8 - 65000 - C;
const bonusMargin = scenarios[2].paymentAtCap - 65000 - C;
assert.equal(controlMargin / bonusMargin, 4);
assert.equal(controlMargin, 8000);
assert.equal(bonusMargin, 2000);
const report = { status: 'passed', assumptionsOnly: true, scenarios, maxFloorFor30kAt20, extraSavingsAt1km, requiredPickupProbabilityRatio: controlMargin / bonusMargin, note: 'Mathematical checks; not observed demand or causal outcomes' };
fs.writeFileSync(path.join(__dirname, 'math-audit.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
